const PRODUCTOS_ACTIVOS = `SELECT P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, P.CODIGO_BARRA,
         P.STOCK_ACTUAL, P.STOCK_CRITICO, U.CODIGO_UNIDAD, U.PERMITE_DECIMALES
  FROM PRODUCTO P JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
  WHERE P.ESTADO_PRODUCTO = 'S'`;

const columnasInsumo = `I.ID_INSUMO, I.NOMBRE_INSUMO, I.STOCK_ACTUAL,
         I.STOCK_CRITICO, I.ID_PROVEEDOR, I.COSTO_UNITARIO,
         U.CODIGO_UNIDAD, U.PERMITE_DECIMALES`;
const desdeInsumo = "FROM INSUMO I JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = I.ID_UNIDAD";
const INSUMOS = `SELECT ${columnasInsumo}, I.ESTADO_ACTIVO ${desdeInsumo}`;
const INSUMOS_ACTIVOS = `SELECT ${columnasInsumo} ${desdeInsumo} WHERE I.ESTADO_ACTIVO = 'S'`;

const ULTIMO_PROVEEDOR_PRODUCTO = `SELECT ID_PRODUCTO, ID_PROVEEDOR FROM (
  SELECT A.ID_PRODUCTO, A.ID_PROVEEDOR, ROW_NUMBER() OVER (
    PARTITION BY A.ID_PRODUCTO ORDER BY A.FECHA_COMPRA DESC NULLS LAST, A.ID_ABASTECIMIENTO DESC
  ) AS POSICION FROM ABASTECIMIENTO_PROVEEDOR A
) WHERE POSICION = 1`;

