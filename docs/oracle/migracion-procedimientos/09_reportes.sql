-- Consultas de reportes. Los filtros, el agrupamiento y el orden se reciben como valores.

CREATE OR REPLACE PROCEDURE SAB_API_REP_RESUMEN_INDICADORES(
  p_actorId IN NUMBER,
  p_anterior IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_caja IN NUMBER,
  p_vendedor IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_metodo IN NUMBER,
  p_desde IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH V AS (SELECT V.ID_VENTA, V.ID_USUARIO, V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, V.FECHA_HORA_VENTA
      FROM VENTA V JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY
        AND (p_caja IS NULL OR T.ID_CAJA = p_caja) AND (p_vendedor IS NULL OR V.ID_USUARIO = p_vendedor)
        AND ((p_producto IS NULL AND p_categoria IS NULL) OR EXISTS (
          SELECT 1 FROM DETALLE_VENTA D JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
          WHERE D.ID_VENTA = V.ID_VENTA AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto) AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria)
        )) AND (p_metodo IS NULL OR EXISTS (
          SELECT 1 FROM PAGO_VENTA M WHERE M.ID_VENTA = V.ID_VENTA AND M.ID_METODO_PAGO = p_metodo
        ))) SELECT
        COUNT(CASE WHEN V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND V.ESTADO_VENTA = 'CONFIRMADA' THEN 1 END) AS TRANSACCIONES,
        NVL(SUM(CASE WHEN V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND V.ESTADO_VENTA = 'CONFIRMADA' THEN TOTAL_VENTA END), 0) AS INGRESOS,
        ROUND(AVG(CASE WHEN V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND V.ESTADO_VENTA = 'CONFIRMADA' THEN TOTAL_VENTA END),2) AS TICKET,
        COUNT(CASE WHEN NOT (V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD')) AND V.ESTADO_VENTA = 'CONFIRMADA' THEN 1 END) AS TRANSACCIONES_ANTERIOR,
        NVL(SUM(CASE WHEN NOT (V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD')) AND V.ESTADO_VENTA = 'CONFIRMADA' THEN TOTAL_VENTA END),0) AS INGRESOS_ANTERIOR,
        ROUND(AVG(CASE WHEN NOT (V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD')) AND V.ESTADO_VENTA = 'CONFIRMADA' THEN TOTAL_VENTA END),2) AS TICKET_ANTERIOR
        FROM V;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_REP_RESUMEN_COMPRAS(
  p_actorId IN NUMBER,
  p_anterior IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_proveedor IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_desde IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH B AS (SELECT A.ID_ABASTECIMIENTO, A.FECHA_COMPRA, A.ID_PROVEEDOR, A.ID_PRODUCTO,
        P.NOMBRE_PRODUCTO AS PRODUCTO, R.RAZON_SOCIAL AS PROVEEDOR, U.CODIGO_UNIDAD AS UNIDAD,
        A.CANTIDAD_COMPRADA AS CANTIDAD, A.COSTO_UNITARIO_COMPRA AS COSTO,
        ROUND(A.CANTIDAD_COMPRADA * A.COSTO_UNITARIO_COMPRA, 2) AS IMPORTE
      FROM ABASTECIMIENTO_PROVEEDOR A JOIN PRODUCTO P ON P.ID_PRODUCTO = A.ID_PRODUCTO
      JOIN PROVEEDOR R ON R.ID_PROVEEDOR = A.ID_PROVEEDOR JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
      WHERE A.FECHA_COMPRA >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND A.FECHA_COMPRA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY
        AND (p_proveedor IS NULL OR A.ID_PROVEEDOR = p_proveedor) AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto)
        AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria)) SELECT
        COUNT(CASE WHEN B.FECHA_COMPRA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') THEN 1 END) AS ABASTECIMIENTOS,
        NVL(SUM(CASE WHEN B.FECHA_COMPRA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') THEN IMPORTE END),0) AS GASTOS,
        NVL(SUM(CASE WHEN NOT (B.FECHA_COMPRA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD')) THEN IMPORTE END),0) AS GASTOS_ANTERIOR FROM B;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_REP_RESUMEN_STOCK(
  p_actorId IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_unidad IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH S AS (SELECT 'Producto' AS TIPO, P.ID_PRODUCTO AS ID, P.NOMBRE_PRODUCTO AS ARTICULO,
        A.NOMBRE_CATEGORIA AS CATEGORIA, U.CODIGO_UNIDAD AS UNIDAD, P.STOCK_ACTUAL, P.STOCK_CRITICO
      FROM PRODUCTO P JOIN CATEGORIA_PRODUCTO A ON A.ID_CATEGORIA = P.ID_CATEGORIA
      JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
      WHERE P.ESTADO_PRODUCTO = 'S' AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto)
        AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria) AND (p_unidad IS NULL OR P.ID_UNIDAD = p_unidad)
      UNION ALL
      SELECT 'Insumo', I.ID_INSUMO, I.NOMBRE_INSUMO, NULL, U.CODIGO_UNIDAD, I.STOCK_ACTUAL, I.STOCK_CRITICO
      FROM INSUMO I JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = I.ID_UNIDAD
      WHERE I.ESTADO_ACTIVO = 'S' AND p_producto IS NULL AND p_categoria IS NULL AND (p_unidad IS NULL OR I.ID_UNIDAD = p_unidad)) SELECT
      COUNT(CASE WHEN TIPO = 'Producto' THEN 1 END) AS PRODUCTOS,
      COUNT(CASE WHEN TIPO = 'Insumo' THEN 1 END) AS INSUMOS,
      COUNT(CASE WHEN TIPO = 'Producto' AND STOCK_ACTUAL <= STOCK_CRITICO THEN 1 END) AS PRODUCTOS_CRITICOS,
      COUNT(CASE WHEN TIPO = 'Insumo' AND STOCK_ACTUAL <= STOCK_CRITICO THEN 1 END) AS INSUMOS_CRITICOS,
      COUNT(CASE WHEN STOCK_ACTUAL = 0 THEN 1 END) AS AGOTADOS FROM S;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_REP_RESUMEN_CAJA(
  p_actorId IN NUMBER,
  p_caja IN NUMBER,
  p_vendedor IN NUMBER,
  p_desde IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_anterior IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH T AS (SELECT T.*, CAST(T.FECHA_HORA_CIERRE AS DATE) - CAST(T.FECHA_HORA_APERTURA AS DATE) AS DURACION_DIAS,
        (T.CIERRE_REAL_EFECTIVO - T.CIERRE_SISTEMA_EFECTIVO
         + T.CIERRE_REAL_TARJETA - T.CIERRE_SISTEMA_TARJETA
         + T.CIERRE_REAL_TRANSFERENCIA - T.CIERRE_SISTEMA_TRANSFERENCIA) AS DESCUADRE
      FROM TURNO_CAJA T WHERE (p_caja IS NULL OR T.ID_CAJA = p_caja)
        AND (p_vendedor IS NULL OR p_vendedor IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE))) SELECT
        COUNT(CASE WHEN ESTADO_TURNO = 'ABIERTO' THEN 1 END) AS ABIERTOS,
        COUNT(CASE WHEN T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY THEN 1 END) AS CERRADOS,
        COUNT(CASE WHEN T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY AND DESCUADRE <> 0 THEN 1 END) AS CON_DESCUADRE,
        NVL(SUM(CASE WHEN T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY THEN DESCUADRE END),0) AS DESCUADRE,
        COUNT(CASE WHEN T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') THEN 1 END) AS CERRADOS_ANTERIOR,
        NVL(SUM(CASE WHEN T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') THEN DESCUADRE END),0) AS DESCUADRE_ANTERIOR
      FROM T WHERE T.ESTADO_TURNO = 'ABIERTO' OR T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY;
END;
