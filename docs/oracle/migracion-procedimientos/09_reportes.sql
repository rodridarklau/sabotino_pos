CREATE OR REPLACE PROCEDURE SAB_API_REP_VENDEDORES_TABLA(
  p_actorId IN NUMBER,
  p_anterior IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_caja IN NUMBER,
  p_vendedor IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_metodo IN NUMBER,
  p_desde IN VARCHAR2,
  p_desplazamiento IN NUMBER,
  p_limite IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH V AS (SELECT V.ID_VENTA, V.ID_USUARIO, V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, V.FECHA_HORA_VENTA
      FROM VENTA V JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY
        AND (p_caja IS NULL OR T.ID_CAJA = p_caja) AND (p_vendedor IS NULL OR V.ID_USUARIO = p_vendedor)
        AND ((p_producto IS NULL AND p_categoria IS NULL) OR EXISTS (
          SELECT 1 FROM DETALLE_VENTA D JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
          WHERE D.ID_VENTA = V.ID_VENTA AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto) AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria)
        )) AND (p_metodo IS NULL OR EXISTS (
          SELECT 1 FROM PAGO_VENTA M WHERE M.ID_VENTA = V.ID_VENTA AND M.ID_METODO_PAGO = p_metodo
        ))), POR_USUARIO AS (
              SELECT V.ID_USUARIO, COUNT(*) AS REGISTRADAS, COUNT(CASE WHEN V.ESTADO_VENTA = 'CONFIRMADA' THEN 1 END) AS TRANSACCIONES,
                NVL(SUM(CASE WHEN V.ESTADO_VENTA = 'CONFIRMADA' THEN V.TOTAL_VENTA END),0) AS INGRESOS,
                ROUND(AVG(CASE WHEN V.ESTADO_VENTA = 'CONFIRMADA' THEN V.TOTAL_VENTA END),2) AS TICKET,
                COUNT(DISTINCT TRUNC(V.FECHA_HORA_VENTA)) AS DIAS_ACTIVOS,
                MIN(V.FECHA_HORA_VENTA) AS PRIMERA, MAX(V.FECHA_HORA_VENTA) AS ULTIMA
              FROM V WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') GROUP BY V.ID_USUARIO
            ), APERTURAS AS (
              SELECT ID_USUARIO_APERTURA AS ID_USUARIO, COUNT(*) AS TURNOS FROM TURNO_CAJA T
              WHERE T.FECHA_HORA_APERTURA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_APERTURA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY AND (p_caja IS NULL OR T.ID_CAJA = p_caja) GROUP BY ID_USUARIO_APERTURA
            )
            SELECT U.NOMBRE_COMPLETO AS RESPONSABLE, NVL(V.REGISTRADAS,0) AS REGISTRADAS,
              NVL(V.TRANSACCIONES,0) AS TRANSACCIONES, NVL(V.INGRESOS,0) AS INGRESOS, V.TICKET,
              NVL(A.TURNOS,0) AS TURNOS, NVL(V.DIAS_ACTIVOS,0) AS DIAS_ACTIVOS,
              TO_CHAR(V.PRIMERA, 'YYYY-MM-DD HH24:MI:SS') AS PRIMERA, TO_CHAR(V.ULTIMA, 'YYYY-MM-DD HH24:MI:SS') AS ULTIMA
            FROM USUARIO U JOIN ROL_USUARIO R ON R.ID_ROL=U.ID_ROL
            LEFT JOIN POR_USUARIO V ON V.ID_USUARIO=U.ID_USUARIO LEFT JOIN APERTURAS A ON A.ID_USUARIO=U.ID_USUARIO
            WHERE R.NOMBRE_ROL='VENDEDOR' AND (p_vendedor IS NULL OR U.ID_USUARIO = p_vendedor)
            ORDER BY INGRESOS DESC,U.ID_USUARIO OFFSET p_desplazamiento ROWS FETCH NEXT p_limite ROWS ONLY;
END;
