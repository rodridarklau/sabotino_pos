CREATE OR REPLACE PROCEDURE SAB_API_REP_VENTAS_ACTIVIDAD(
  p_actorId IN NUMBER,
  p_anterior IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_caja IN NUMBER,
  p_vendedor IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_metodo IN NUMBER,
  p_desde IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH V AS (SELECT V.ID_VENTA, V.ID_USUARIO, V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, V.FECHA_HORA_VENTA
      FROM VENTA V JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY
        AND (p_caja IS NULL OR T.ID_CAJA = p_caja) AND (p_vendedor IS NULL OR V.ID_USUARIO = p_vendedor)
        AND ((p_producto IS NULL AND p_categoria IS NULL) OR EXISTS (
          SELECT 1 FROM DETALLE_VENTA D JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
          WHERE D.ID_VENTA = V.ID_VENTA AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto) AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria)
        )) AND (p_metodo IS NULL OR EXISTS (
          SELECT 1 FROM PAGO_VENTA M WHERE M.ID_VENTA = V.ID_VENTA AND M.ID_METODO_PAGO = p_metodo
        ))), DIAS AS (SELECT TO_DATE(p_desde,'YYYY-MM-DD') + LEVEL - 1 AS DIA
              FROM DUAL CONNECT BY LEVEL <= TO_DATE(p_hasta,'YYYY-MM-DD') - TO_DATE(p_desde,'YYYY-MM-DD') + 1),
              ACTIVIDAD AS (SELECT DIAS.DIA, COUNT(V.ID_VENTA) AS TRANSACCIONES
               FROM DIAS LEFT JOIN V ON V.FECHA_HORA_VENTA >= DIAS.DIA AND V.FECHA_HORA_VENTA < DIAS.DIA + 1
                 AND V.ESTADO_VENTA = 'CONFIRMADA' GROUP BY DIAS.DIA),
              EXTREMOS AS (SELECT DIA, TRANSACCIONES,
                ROW_NUMBER() OVER(ORDER BY TRANSACCIONES DESC, DIA) MAYOR,
                ROW_NUMBER() OVER(ORDER BY TRANSACCIONES, DIA) MENOR FROM ACTIVIDAD)
              SELECT TO_CHAR(DIA,'YYYY-MM-DD') AS FECHA, TRANSACCIONES, MAYOR, MENOR
              FROM EXTREMOS WHERE MAYOR = 1 OR MENOR = 1 ORDER BY MAYOR;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_REP_VENTAS_TABLA(
  p_actorId IN NUMBER,
  p_anterior IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_caja IN NUMBER,
  p_vendedor IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_metodo IN NUMBER,
  p_desde IN VARCHAR2,
  p_estado IN VARCHAR2,
  p_periodo IN VARCHAR2,
  p_agrupacion IN VARCHAR2,
  p_desplazamiento IN NUMBER,
  p_limite IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH V AS (SELECT V.ID_VENTA, V.ID_USUARIO, V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, V.FECHA_HORA_VENTA
      FROM VENTA V JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY
        AND (p_caja IS NULL OR T.ID_CAJA = p_caja) AND (p_vendedor IS NULL OR V.ID_USUARIO = p_vendedor)
        AND ((p_producto IS NULL AND p_categoria IS NULL) OR EXISTS (
          SELECT 1 FROM DETALLE_VENTA D JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
          WHERE D.ID_VENTA = V.ID_VENTA AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto) AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria)
        )) AND (p_metodo IS NULL OR EXISTS (
          SELECT 1 FROM PAGO_VENTA M WHERE M.ID_VENTA = V.ID_VENTA AND M.ID_METODO_PAGO = p_metodo
        ))) SELECT V.ID_VENTA AS ID, TO_CHAR(V.FECHA_HORA_VENTA, 'YYYY-MM-DD HH24:MI:SS') AS FECHA,
              U.NOMBRE_COMPLETO AS RESPONSABLE, C.NOMBRE_CAJA AS CAJA, V.ESTADO_VENTA AS ESTADO, V.TOTAL_VENTA AS IMPORTE
              FROM V JOIN USUARIO U ON U.ID_USUARIO = V.ID_USUARIO
              JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
              WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND (p_estado = 'TODOS' OR V.ESTADO_VENTA = p_estado)
                AND (p_periodo IS NULL OR TO_CHAR(TRUNC(V.FECHA_HORA_VENTA, CASE p_agrupacion WHEN 'semana' THEN 'IW' WHEN 'mes' THEN 'MM' WHEN 'anio' THEN 'YYYY' ELSE 'DD' END), 'YYYY-MM-DD') = p_periodo)
              ORDER BY V.FECHA_HORA_VENTA DESC, V.ID_VENTA DESC OFFSET p_desplazamiento ROWS FETCH NEXT p_limite ROWS ONLY;
END;
