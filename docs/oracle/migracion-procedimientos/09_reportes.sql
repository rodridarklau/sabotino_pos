CREATE OR REPLACE PROCEDURE SAB_API_REP_PAGOS_METODOS(
  p_actorId IN NUMBER,
  p_anterior IN VARCHAR2,
  p_hasta IN VARCHAR2,
  p_caja IN NUMBER,
  p_vendedor IN NUMBER,
  p_producto IN NUMBER,
  p_categoria IN NUMBER,
  p_metodo IN NUMBER,
  p_desde IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    WITH V AS (SELECT V.ID_VENTA, V.ID_USUARIO, V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, V.FECHA_HORA_VENTA
      FROM VENTA V JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      WHERE V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_anterior, 'YYYY-MM-DD') AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY
        AND (p_caja IS NULL OR T.ID_CAJA = p_caja) AND (p_vendedor IS NULL OR V.ID_USUARIO = p_vendedor)
        AND ((p_producto IS NULL AND p_categoria IS NULL) OR EXISTS (
          SELECT 1 FROM DETALLE_VENTA D JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
          WHERE D.ID_VENTA = V.ID_VENTA AND (p_producto IS NULL OR P.ID_PRODUCTO = p_producto) AND (p_categoria IS NULL OR P.ID_CATEGORIA = p_categoria)
        )) AND (p_metodo IS NULL OR EXISTS (
          SELECT 1 FROM PAGO_VENTA M WHERE M.ID_VENTA = V.ID_VENTA AND M.ID_METODO_PAGO = p_metodo
        ))), MONTOS AS (SELECT M.ID_METODO_PAGO, COUNT(*) AS PAGOS, SUM(P.MONTO_PAGADO) AS IMPORTE
