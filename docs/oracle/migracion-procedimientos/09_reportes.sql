                WHERE V.ESTADO_VENTA='CONFIRMADA' AND (T.ESTADO_TURNO = 'ABIERTO' OR T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY)
              ), COBROS AS (SELECT ID_TURNO_CAJA,
                SUM(CASE WHEN NOMBRE_METODO='EFECTIVO' THEN MONTO_PAGADO ELSE 0 END) EFECTIVO,
                SUM(CASE WHEN NOMBRE_METODO='TARJETA' THEN MONTO_PAGADO ELSE 0 END) TARJETA,
                SUM(CASE WHEN NOMBRE_METODO='TRANSFERENCIA' THEN MONTO_PAGADO ELSE 0 END) TRANSFERENCIA
                FROM PAGOS GROUP BY ID_TURNO_CAJA), CONFIRMADAS AS (
                SELECT V.ID_TURNO_CAJA, COUNT(*) VENTAS, SUM(V.TOTAL_VENTA) INGRESOS FROM T
                JOIN VENTA V ON V.ID_TURNO_CAJA=T.ID_TURNO_CAJA
                WHERE V.ESTADO_VENTA='CONFIRMADA' AND (T.ESTADO_TURNO = 'ABIERTO' OR T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY) GROUP BY V.ID_TURNO_CAJA
              )
              SELECT T.ID_TURNO_CAJA AS ID, C.NOMBRE_CAJA AS CAJA, T.ESTADO_TURNO AS ESTADO,
                A.NOMBRE_COMPLETO AS APERTURA_POR, B.NOMBRE_COMPLETO AS CIERRE_POR,
                TO_CHAR(T.FECHA_HORA_APERTURA, 'YYYY-MM-DD HH24:MI:SS') AS APERTURA, TO_CHAR(T.FECHA_HORA_CIERRE, 'YYYY-MM-DD HH24:MI:SS') AS CIERRE,
                ROUND(NVL(T.DURACION_DIAS, CAST(SYSTIMESTAMP AS DATE)-CAST(T.FECHA_HORA_APERTURA AS DATE))*1440) AS MINUTOS,
                T.INICIAL_EFECTIVO, NVL(V.VENTAS,0) AS TRANSACCIONES, NVL(V.INGRESOS,0) AS INGRESOS,
                CASE WHEN T.ESTADO_TURNO='ABIERTO'
                  THEN T.INICIAL_EFECTIVO + NVL(P.EFECTIVO,0) ELSE T.CIERRE_SISTEMA_EFECTIVO END AS ESP_EFECTIVO,
                  T.CIERRE_REAL_EFECTIVO AS REAL_EFECTIVO,
                CASE WHEN T.ESTADO_TURNO='ABIERTO'
                  THEN T.INICIAL_TARJETA + NVL(P.TARJETA,0) ELSE T.CIERRE_SISTEMA_TARJETA END AS ESP_TARJETA,
                  T.CIERRE_REAL_TARJETA AS REAL_TARJETA,
                CASE WHEN T.ESTADO_TURNO='ABIERTO'
                  THEN T.INICIAL_TRANSFERENCIA + NVL(P.TRANSFERENCIA,0) ELSE T.CIERRE_SISTEMA_TRANSFERENCIA END AS ESP_TRANSFERENCIA,
                  T.CIERRE_REAL_TRANSFERENCIA AS REAL_TRANSFERENCIA,
                T.DESCUADRE
              FROM T JOIN CAJA_TERMINAL C ON C.ID_CAJA=T.ID_CAJA JOIN USUARIO A ON A.ID_USUARIO=T.ID_USUARIO_APERTURA
              LEFT JOIN USUARIO B ON B.ID_USUARIO=T.ID_USUARIO_CIERRE LEFT JOIN COBROS P ON P.ID_TURNO_CAJA=T.ID_TURNO_CAJA
              LEFT JOIN CONFIRMADAS V ON V.ID_TURNO_CAJA=T.ID_TURNO_CAJA
              WHERE (T.ESTADO_TURNO = 'ABIERTO' OR T.FECHA_HORA_CIERRE >= TO_TIMESTAMP(p_desde, 'YYYY-MM-DD') AND T.FECHA_HORA_CIERRE < TO_TIMESTAMP(p_hasta, 'YYYY-MM-DD') + INTERVAL '1' DAY) ORDER BY T.FECHA_HORA_APERTURA DESC,T.ID_TURNO_CAJA DESC OFFSET p_desplazamiento ROWS FETCH NEXT p_limite ROWS ONLY;
END;
