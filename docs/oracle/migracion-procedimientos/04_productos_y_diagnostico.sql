-- Catálogos y lecturas de Productos. Las operaciones con bloqueo reutilizan los gestores.

CREATE OR REPLACE PROCEDURE SAB_API_PRODUCTOS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT P.* FROM PRODUCTO P ORDER BY P.ID_PRODUCTO DESC FETCH FIRST 20 ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_PRODUCTOS_DUENO(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT P.*, PR.RAZON_SOCIAL AS PROVEEDOR_ACTUAL FROM PRODUCTO P
    LEFT JOIN (SELECT ID_PRODUCTO, ID_PROVEEDOR FROM (
      SELECT A.ID_PRODUCTO, A.ID_PROVEEDOR, ROW_NUMBER() OVER (
        PARTITION BY A.ID_PRODUCTO ORDER BY A.FECHA_COMPRA DESC NULLS LAST, A.ID_ABASTECIMIENTO DESC
      ) AS POSICION FROM ABASTECIMIENTO_PROVEEDOR A
    ) WHERE POSICION = 1) A ON A.ID_PRODUCTO = P.ID_PRODUCTO
    LEFT JOIN PROVEEDOR PR ON PR.ID_PROVEEDOR = A.ID_PROVEEDOR
    ORDER BY P.ID_PRODUCTO DESC FETCH FIRST 20 ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_PRODUCTO_CATEGORIAS(
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT ID_CATEGORIA, NOMBRE_CATEGORIA, DESCRIPCION_CATEGORIA
           FROM CATEGORIA_PRODUCTO ORDER BY NOMBRE_CATEGORIA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_PRODUCTO_MARCAS(
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT ID_MARCA, NOMBRE_MARCA, ORIGEN_ELABORACION
           FROM MARCA ORDER BY NOMBRE_MARCA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_PRODUCTO_UNIDADES(
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT ID_UNIDAD, CODIGO_UNIDAD, NOMBRE_UNIDAD, PERMITE_DECIMALES
           FROM UNIDAD_MEDIDA ORDER BY NOMBRE_UNIDAD;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_ALERTAS_PRODUCTOS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, P.CODIGO_BARRA,
        P.STOCK_ACTUAL, P.STOCK_CRITICO, U.CODIGO_UNIDAD
      FROM PRODUCTO P
      JOIN UNIDAD_MEDIDA U ON P.ID_UNIDAD = U.ID_UNIDAD
      WHERE P.ESTADO_PRODUCTO = 'S' AND P.STOCK_ACTUAL <= P.STOCK_CRITICO
      ORDER BY P.STOCK_ACTUAL ASC, P.NOMBRE_PRODUCTO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_EDITAR_PRODUCTO(
  p_actorId IN NUMBER, p_id IN NUMBER, p_categoria IN NUMBER, p_unidad IN NUMBER,
  p_marca IN NUMBER, p_barra IN VARCHAR2, p_nombre IN VARCHAR2,
  p_costo IN NUMBER, p_precio IN NUMBER, p_stockCritico IN NUMBER
) IS
  CURSOR c_producto IS
    SELECT ESTADO_PRODUCTO FROM PRODUCTO WHERE ID_PRODUCTO = p_id FOR UPDATE;
  l_estado PRODUCTO.ESTADO_PRODUCTO%TYPE;
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN c_producto;
  FETCH c_producto INTO l_estado;
  IF c_producto%NOTFOUND THEN
    RAISE_APPLICATION_ERROR(-20011, 'Producto no encontrado');
  END IF;
  CLOSE c_producto;
  IF l_estado <> 'S' THEN
    RAISE_APPLICATION_ERROR(-20701, 'No se puede editar un producto inactivo');
  END IF;
  SAB_U_PRODUCTO(p_actorId, p_id, p_categoria, p_unidad, p_marca, p_barra,
    p_nombre, p_costo, p_precio, p_stockCritico, 'S');
EXCEPTION WHEN OTHERS THEN
  IF c_producto%ISOPEN THEN
    CLOSE c_producto;
  END IF;
  ROLLBACK;
  RAISE;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_BAJA_PRODUCTO(p_actorId IN NUMBER, p_id IN NUMBER) IS
  CURSOR c_producto IS
    SELECT ESTADO_PRODUCTO FROM PRODUCTO WHERE ID_PRODUCTO = p_id FOR UPDATE;
  l_estado PRODUCTO.ESTADO_PRODUCTO%TYPE;
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN c_producto;
  FETCH c_producto INTO l_estado;
  IF c_producto%NOTFOUND THEN
    RAISE_APPLICATION_ERROR(-20014, 'Producto no encontrado');
  END IF;
  CLOSE c_producto;
  IF l_estado = 'N' THEN
    RAISE_APPLICATION_ERROR(-20702, 'El producto ya está desactivado');
  END IF;
  SAB_D_PRODUCTO(p_actorId, p_id);
EXCEPTION WHEN OTHERS THEN
  IF c_producto%ISOPEN THEN
    CLOSE c_producto;
  END IF;
  ROLLBACK;
  RAISE;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_TABLAS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT TABLE_NAME FROM USER_TABLES ORDER BY TABLE_NAME;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_TOTAL_TABLAS(
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT USER AS USUARIO, (SELECT COUNT(*) FROM USER_TABLES) AS TOTAL_TABLAS FROM DUAL;
END;
/
