-- Resumen de Inicio y verificación de productos con imágenes.

CREATE OR REPLACE PROCEDURE SAB_API_INICIO_VENTAS(
  p_hoy IN VARCHAR2,
  p_actorId IN NUMBER,
  p_dueno IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  IF p_dueno IS NULL OR p_dueno <> SAB_F_ES_DUENO(p_actorId) THEN
    RAISE_APPLICATION_ERROR(-20003, 'Alcance inválido');
  END IF;
  OPEN p_resultado FOR
    SELECT COUNT(*) AS CANTIDAD,
            NVL(SUM(V.TOTAL_VENTA), 0) AS TOTAL
          FROM VENTA V WHERE V.ESTADO_VENTA = 'CONFIRMADA'
            AND V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_hoy, 'YYYY-MM-DD')
            AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hoy, 'YYYY-MM-DD') + INTERVAL '1' DAY
            AND (p_dueno = 1 OR V.ID_USUARIO = p_actorId);
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_INICIO_TURNOS(
  p_actorId IN NUMBER,
  p_nombre IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT T.ID_TURNO_CAJA, C.NOMBRE_CAJA,
            TO_CHAR(T.FECHA_HORA_APERTURA, 'HH24:MI DD/MM/YYYY') AS APERTURA
          FROM TURNO_CAJA T JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
          WHERE T.ESTADO_TURNO = 'ABIERTO' AND C.NOMBRE_CAJA = p_nombre AND C.ESTADO_OPERATIVO = 'S'
          ORDER BY T.FECHA_HORA_APERTURA DESC, T.ID_TURNO_CAJA DESC;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_ALERTAS_INSUMOS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT I.ID_INSUMO, I.NOMBRE_INSUMO, I.STOCK_ACTUAL,
             I.STOCK_CRITICO, I.ID_PROVEEDOR, I.COSTO_UNITARIO,
             U.CODIGO_UNIDAD, U.PERMITE_DECIMALES FROM INSUMO I JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = I.ID_UNIDAD WHERE I.ESTADO_ACTIVO = 'S' AND I.STOCK_ACTUAL <= I.STOCK_CRITICO ORDER BY I.NOMBRE_INSUMO, I.ID_INSUMO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_IMAGEN_PRODUCTO(
  p_actorId IN NUMBER,
  p_id IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT ID_PRODUCTO FROM PRODUCTO WHERE ID_PRODUCTO = p_id;
END;
/
