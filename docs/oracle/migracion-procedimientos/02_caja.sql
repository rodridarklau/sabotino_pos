CREATE OR REPLACE PROCEDURE SAB_API_CAJA_POR_NOMBRE(
  p_actorId IN NUMBER,
  p_nombre IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT ID_CAJA, NOMBRE_CAJA, ESTADO_OPERATIVO
    FROM CAJA_TERMINAL WHERE NOMBRE_CAJA = p_nombre AND NOMBRE_CAJA = 'MAIN';
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_ABIERTOS(
  p_actorId IN NUMBER,
  p_dueno IN NUMBER,
  p_cajaId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  IF p_dueno IS NULL OR p_dueno <> SAB_F_ES_DUENO(p_actorId) THEN
    RAISE_APPLICATION_ERROR(-20003, 'Alcance inválido');
  END IF;
  OPEN p_resultado FOR
    SELECT T.ID_TURNO_CAJA, T.ID_CAJA, C.NOMBRE_CAJA, T.ESTADO_TURNO,
        TO_CHAR(T.FECHA_HORA_APERTURA, 'DD/MM/YYYY HH24:MI:SS') AS APERTURA,
        TO_CHAR(T.FECHA_HORA_CIERRE, 'DD/MM/YYYY HH24:MI:SS') AS CIERRE,
        A.NOMBRE_COMPLETO AS RESPONSABLE_APERTURA, B.NOMBRE_COMPLETO AS RESPONSABLE_CIERRE,
        T.INICIAL_EFECTIVO, T.INICIAL_TARJETA, T.INICIAL_TRANSFERENCIA,
        T.CIERRE_SISTEMA_EFECTIVO, T.CIERRE_SISTEMA_TARJETA, T.CIERRE_SISTEMA_TRANSFERENCIA,
        T.CIERRE_REAL_EFECTIVO, T.CIERRE_REAL_TARJETA, T.CIERRE_REAL_TRANSFERENCIA
      FROM TURNO_CAJA T JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
      JOIN USUARIO A ON A.ID_USUARIO = T.ID_USUARIO_APERTURA
      LEFT JOIN USUARIO B ON B.ID_USUARIO = T.ID_USUARIO_CIERRE
      WHERE (p_dueno = 1 OR T.ESTADO_TURNO = 'ABIERTO'
        OR p_actorId IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE)) AND T.ID_CAJA = p_cajaId
        AND T.ESTADO_TURNO = 'ABIERTO' ORDER BY T.ID_TURNO_CAJA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_RESUMEN_DIA(
  p_actorId IN NUMBER,
  p_cajaId IN NUMBER,
  p_hoy IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT COUNT(V.ID_VENTA) AS CANTIDAD, NVL(SUM(V.TOTAL_VENTA), 0) AS TOTAL
    FROM CAJA_TERMINAL C LEFT JOIN TURNO_CAJA T ON T.ID_CAJA = C.ID_CAJA
    LEFT JOIN VENTA V ON V.ID_TURNO_CAJA = T.ID_TURNO_CAJA
      AND V.ESTADO_VENTA = 'CONFIRMADA'
      AND V.FECHA_HORA_VENTA >= TO_TIMESTAMP(p_hoy, 'YYYY-MM-DD')
      AND V.FECHA_HORA_VENTA < TO_TIMESTAMP(p_hoy, 'YYYY-MM-DD') + INTERVAL '1' DAY
    WHERE C.ID_CAJA = p_cajaId AND C.NOMBRE_CAJA = 'MAIN'
    GROUP BY C.ID_CAJA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_HISTORIAL(
