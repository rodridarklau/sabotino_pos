CREATE OR REPLACE PROCEDURE SAB_API_CAJA_TURNO_PAGOS(
  p_actorId IN NUMBER,
  p_turnoId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
  l_dueno NUMBER;
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  l_dueno := SAB_F_ES_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT M.NOMBRE_METODO, NVL(SUM(P.MONTO_PAGADO), 0) AS TOTAL
        FROM METODO_PAGO M LEFT JOIN (
          SELECT P.ID_METODO_PAGO, P.MONTO_PAGADO FROM PAGO_VENTA P
          JOIN VENTA V ON V.ID_VENTA = P.ID_VENTA
          WHERE V.ID_TURNO_CAJA = p_turnoId AND V.ESTADO_VENTA = 'CONFIRMADA'
        ) P ON P.ID_METODO_PAGO = M.ID_METODO_PAGO
        WHERE EXISTS (
          SELECT 1 FROM TURNO_CAJA T WHERE T.ID_TURNO_CAJA = p_turnoId
            AND (l_dueno = 1 OR T.ESTADO_TURNO = 'ABIERTO'
                 OR p_actorId IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE))
        )
        GROUP BY M.NOMBRE_METODO ORDER BY M.NOMBRE_METODO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_TURNO_VENTAS(
  p_actorId IN NUMBER,
  p_dueno IN NUMBER,
  p_turnoId IN NUMBER,
  p_desplazamiento IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  IF p_dueno IS NULL OR p_dueno <> SAB_F_ES_DUENO(p_actorId) THEN
    RAISE_APPLICATION_ERROR(-20003, 'Alcance inválido');
  END IF;
  OPEN p_resultado FOR
    SELECT V.ID_VENTA, U.NOMBRE_COMPLETO AS RESPONSABLE, V.ESTADO_VENTA,
          V.TOTAL_VENTA, TO_CHAR(V.FECHA_HORA_VENTA, 'DD/MM/YYYY HH24:MI:SS') AS FECHA
        FROM VENTA V JOIN USUARIO U ON U.ID_USUARIO = V.ID_USUARIO
        JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
        WHERE V.ID_TURNO_CAJA = p_turnoId AND (p_dueno = 1 OR V.ID_USUARIO = p_actorId)
          AND (p_dueno = 1 OR T.ESTADO_TURNO = 'ABIERTO'
               OR p_actorId IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE))
        ORDER BY V.FECHA_HORA_VENTA DESC, V.ID_VENTA DESC
        OFFSET p_desplazamiento ROWS FETCH NEXT 26 ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_TURNO_RESUMEN(
  p_actorId IN NUMBER,
  p_turnoId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
  l_dueno NUMBER;
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  l_dueno := SAB_F_ES_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT COUNT(V.ID_VENTA) AS CANTIDAD, NVL(SUM(V.TOTAL_VENTA), 0) AS TOTAL
    FROM TURNO_CAJA T LEFT JOIN VENTA V ON V.ID_TURNO_CAJA = T.ID_TURNO_CAJA
      AND V.ESTADO_VENTA = 'CONFIRMADA'
    WHERE T.ID_TURNO_CAJA = p_turnoId
      AND (l_dueno = 1 OR T.ESTADO_TURNO = 'ABIERTO'
           OR p_actorId IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE))
    GROUP BY T.ID_TURNO_CAJA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_TURNO_BORRADORES(
  p_actorId IN NUMBER,
  p_turnoId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
  l_dueno NUMBER;
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  l_dueno := SAB_F_ES_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT COUNT(V.ID_VENTA) AS BORRADORES
    FROM TURNO_CAJA T LEFT JOIN VENTA V ON V.ID_TURNO_CAJA = T.ID_TURNO_CAJA
      AND V.ESTADO_VENTA = 'BORRADOR'
    WHERE T.ID_TURNO_CAJA = p_turnoId
      AND (l_dueno = 1 OR T.ESTADO_TURNO = 'ABIERTO'
           OR p_actorId IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE))
    GROUP BY T.ID_TURNO_CAJA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_CAJA_TURNO_EVENTOS(
  p_actorId IN NUMBER,
  p_turnoId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
  l_dueno NUMBER;
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  l_dueno := SAB_F_ES_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT L.ID_LOG_CAJA, L.TIPO_OPERACION, L.DESCUADRE_TOTAL,
          U.NOMBRE_COMPLETO AS RESPONSABLE, TO_CHAR(L.FECHA_HORA_REGISTRO, 'DD/MM/YYYY HH24:MI:SS') AS FECHA
        FROM LOG_AUDITORIA_CAJA L JOIN USUARIO U ON U.ID_USUARIO = L.ID_USUARIO
    JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = L.ID_TURNO_CAJA
    WHERE T.ID_TURNO_CAJA = p_turnoId
      AND (l_dueno = 1 OR T.ESTADO_TURNO = 'ABIERTO'
           OR p_actorId IN (T.ID_USUARIO_APERTURA, T.ID_USUARIO_CIERRE))
    ORDER BY L.ID_LOG_CAJA;
END;
/
