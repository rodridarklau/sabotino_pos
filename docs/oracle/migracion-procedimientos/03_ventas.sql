-- Consultas de Ventas. Los métodos de pago reutilizan SAB_UI_L_METODOS_PAGO.

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_TURNOS(
  p_actorId IN NUMBER,
  p_nombre IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT T.ID_TURNO_CAJA, C.NOMBRE_CAJA
        FROM TURNO_CAJA T JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
        WHERE T.ESTADO_TURNO = 'ABIERTO' AND C.NOMBRE_CAJA = p_nombre
        AND C.NOMBRE_CAJA = 'MAIN' AND C.ESTADO_OPERATIVO = 'S' ORDER BY T.ID_TURNO_CAJA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_CATALOGO(
  p_actorId IN NUMBER,
  p_dueno IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  IF p_dueno IS NULL OR p_dueno <> SAB_F_ES_DUENO(p_actorId) THEN
    RAISE_APPLICATION_ERROR(-20003, 'Alcance inválido');
  END IF;
  OPEN p_resultado FOR
    SELECT P.*, (
        SELECT COUNT(DISTINCT V.ID_VENTA) FROM DETALLE_VENTA D JOIN VENTA V ON V.ID_VENTA = D.ID_VENTA
        WHERE D.ID_PRODUCTO = P.ID_PRODUCTO AND V.ESTADO_VENTA = 'CONFIRMADA'
          AND V.FECHA_HORA_VENTA >= CAST(SYSTIMESTAMP AS TIMESTAMP) - INTERVAL '30' DAY
          AND (p_dueno = 1 OR V.ID_USUARIO = p_actorId)
      ) AS VENTAS_RECIENTES FROM (SELECT P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, P.CODIGO_BARRA,
        P.PRECIO_VENTA_ACTUAL, P.STOCK_ACTUAL, P.STOCK_CRITICO, P.ID_CATEGORIA,
        C.NOMBRE_CATEGORIA, U.CODIGO_UNIDAD, U.PERMITE_DECIMALES
      FROM PRODUCTO P JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
      JOIN CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
      WHERE P.ESTADO_PRODUCTO = 'S') P ORDER BY P.NOMBRE_PRODUCTO, P.ID_PRODUCTO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_HISTORIAL(
  p_actorId IN NUMBER,
  p_dueno IN NUMBER,
  p_estado IN VARCHAR2,
  p_buscar IN VARCHAR2,
  p_desplazamiento IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  IF p_dueno IS NULL OR p_dueno <> SAB_F_ES_DUENO(p_actorId) THEN
    RAISE_APPLICATION_ERROR(-20003, 'Alcance inválido');
  END IF;
  OPEN p_resultado FOR
    SELECT V.ID_VENTA, V.ID_USUARIO, U.NOMBRE_COMPLETO AS RESPONSABLE,
        TO_CHAR(V.FECHA_HORA_VENTA, 'DD/MM/YYYY HH24:MI:SS') AS FECHA,
        V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, C.NOMBRE_CAJA
      FROM VENTA V JOIN USUARIO U ON U.ID_USUARIO = V.ID_USUARIO
      JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
      WHERE (p_dueno = 1 OR V.ID_USUARIO = p_actorId)
        AND (p_estado IS NULL OR V.ESTADO_VENTA = p_estado)
        AND (p_buscar IS NULL OR INSTR(LOWER(U.NOMBRE_COMPLETO), LOWER(p_buscar)) > 0
             OR TO_CHAR(V.ID_VENTA) = p_buscar)
        ORDER BY V.FECHA_HORA_VENTA DESC, V.ID_VENTA DESC
        OFFSET p_desplazamiento ROWS FETCH NEXT 26 ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_CABECERA(
  p_actorId IN NUMBER,
  p_dueno IN NUMBER,
  p_ventaId IN NUMBER,
  p_comprobante IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  IF p_dueno IS NULL OR p_dueno <> SAB_F_ES_DUENO(p_actorId) THEN
    RAISE_APPLICATION_ERROR(-20003, 'Alcance inválido');
  END IF;
  OPEN p_resultado FOR
    SELECT V.ID_VENTA, V.ID_USUARIO, U.NOMBRE_COMPLETO AS RESPONSABLE,
        TO_CHAR(V.FECHA_HORA_VENTA, 'DD/MM/YYYY HH24:MI:SS') AS FECHA,
        V.ID_TURNO_CAJA, V.ESTADO_VENTA, V.TOTAL_VENTA, C.NOMBRE_CAJA
      FROM VENTA V JOIN USUARIO U ON U.ID_USUARIO = V.ID_USUARIO
      JOIN TURNO_CAJA T ON T.ID_TURNO_CAJA = V.ID_TURNO_CAJA
      JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
      WHERE (p_dueno = 1 OR V.ID_USUARIO = p_actorId) AND V.ID_VENTA = p_ventaId
        AND (p_comprobante = 0 OR V.ESTADO_VENTA = 'CONFIRMADA');
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_DETALLE(
  p_actorId IN NUMBER,
  p_ventaId IN NUMBER,
  p_comprobante IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
  l_dueno NUMBER;
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  l_dueno := SAB_F_ES_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT D.ID_DETALLE_VENTA, P.NOMBRE_PRODUCTO, U.CODIGO_UNIDAD,
          D.CANTIDAD, D.PRECIO_UNITARIO_HISTORICO, D.SUBTOTAL_LINEA
        FROM DETALLE_VENTA D JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
        JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
    JOIN VENTA V ON V.ID_VENTA = D.ID_VENTA
    WHERE V.ID_VENTA = p_ventaId AND (l_dueno = 1 OR V.ID_USUARIO = p_actorId)
      AND (p_comprobante = 0 OR V.ESTADO_VENTA = 'CONFIRMADA')
    ORDER BY D.ID_DETALLE_VENTA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_PAGOS(
  p_actorId IN NUMBER,
  p_ventaId IN NUMBER,
  p_comprobante IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
  l_dueno NUMBER;
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  l_dueno := SAB_F_ES_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT P.ID_PAGO_VENTA, M.NOMBRE_METODO, P.MONTO_PAGADO, P.CODIGO_COMPROBANTE
        FROM PAGO_VENTA P JOIN METODO_PAGO M ON M.ID_METODO_PAGO = P.ID_METODO_PAGO
    JOIN VENTA V ON V.ID_VENTA = P.ID_VENTA
    WHERE V.ID_VENTA = p_ventaId AND (l_dueno = 1 OR V.ID_USUARIO = p_actorId)
      AND (p_comprobante = 0 OR V.ESTADO_VENTA = 'CONFIRMADA')
    ORDER BY P.ID_PAGO_VENTA;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_TURNO_VALIDO(
  p_actorId IN NUMBER,
  p_turnoId IN NUMBER,
  p_nombre IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT T.ID_TURNO_CAJA FROM TURNO_CAJA T
        JOIN CAJA_TERMINAL C ON C.ID_CAJA = T.ID_CAJA
        WHERE T.ID_TURNO_CAJA = p_turnoId AND T.ESTADO_TURNO = 'ABIERTO'
          AND C.NOMBRE_CAJA = p_nombre AND C.NOMBRE_CAJA = 'MAIN' AND C.ESTADO_OPERATIVO = 'S';
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_PRODUCTOS(
  p_actorId IN NUMBER,
  p_ids IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, P.CODIGO_BARRA,
        P.PRECIO_VENTA_ACTUAL, P.STOCK_ACTUAL, P.STOCK_CRITICO, P.ID_CATEGORIA,
        C.NOMBRE_CATEGORIA, U.CODIGO_UNIDAD, U.PERMITE_DECIMALES
      FROM PRODUCTO P JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
      JOIN CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
      WHERE P.ESTADO_PRODUCTO = 'S'
        AND P.ID_PRODUCTO IN (SELECT j.id FROM JSON_TABLE(p_ids, '$[*]' COLUMNS (id NUMBER PATH '$')) j);
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENTA_PROPIA(
  p_actorId IN NUMBER,
  p_ventaId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_USUARIO(p_actorId);
  OPEN p_resultado FOR
    SELECT ID_VENTA FROM VENTA WHERE ID_VENTA = p_ventaId AND ID_USUARIO = p_actorId;
END;
/
