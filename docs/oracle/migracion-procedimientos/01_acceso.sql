-- Estado inicial público, credenciales y vigencia de la sesión.

CREATE OR REPLACE PROCEDURE SAB_API_ESTADO_INICIAL(
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT (SELECT COUNT(*) FROM USUARIO) AS TOTAL_USUARIOS,
           (SELECT COUNT(*) FROM ROL_USUARIO WHERE NOMBRE_ROL = 'DUENO' AND ESTADO_ACTIVO = 'S') AS ROLES_DUENO
    FROM DUAL;
END;
/


CREATE OR REPLACE PROCEDURE SAB_API_CREDENCIALES(
  p_username IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT
             U.ID_USUARIO,
             U.USERNAME,
             U.NOMBRE_COMPLETO,
             U.PASSWORD_HASH,
             RAWTOHEX(STANDARD_HASH(U.PASSWORD_HASH, 'SHA256')) AS VERSION_CUENTA,
             R.NOMBRE_ROL
           FROM USUARIO U
           JOIN ROL_USUARIO R ON U.ID_ROL = R.ID_ROL
           WHERE UPPER(U.USERNAME) = UPPER(p_username)
             AND U.ESTADO_USUARIO = 'S'
             AND R.ESTADO_ACTIVO = 'S';
END;
/


CREATE OR REPLACE PROCEDURE SAB_API_VERSION_SESION(
  p_actorId IN NUMBER,
  p_rol IN VARCHAR2,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT RAWTOHEX(STANDARD_HASH(U.PASSWORD_HASH, 'SHA256')) AS VERSION_CUENTA
            FROM USUARIO U JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
            WHERE U.ID_USUARIO = p_actorId AND U.ESTADO_USUARIO = 'S'
              AND R.ESTADO_ACTIVO = 'S' AND R.NOMBRE_ROL = p_rol;
END;
/


CREATE OR REPLACE PROCEDURE SAB_API_ROL_ACTIVO(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  OPEN p_resultado FOR
    SELECT R.NOMBRE_ROL FROM USUARIO U
          JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
          WHERE U.ID_USUARIO = p_actorId AND U.ESTADO_USUARIO = 'S' AND R.ESTADO_ACTIVO = 'S';
END;
/
