-- Permisos y lecturas de Inventario. Los ajustes siguen en los gestores de Oracle.

CREATE OR REPLACE PROCEDURE SAB_API_ES_DUENO(p_actorId IN NUMBER, p_permitido OUT NUMBER) IS
BEGIN
  p_permitido := SAB_F_ES_DUENO(p_actorId);
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_INVENTARIO_HISTORIAL(
  p_actorId IN NUMBER,
  p_desplazamiento IN NUMBER,
  p_limite IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT A.ID_AJUSTE, P.NOMBRE_PRODUCTO,
            TO_CHAR(A.FECHA_HORA_AJUSTE, 'DD/MM/YYYY HH24:MI:SS') AS FECHA,
            A.CANTIDAD_AJUSTADA, T.NOMBRE_TIPO_AJUSTE, T.FACTOR_OPERACION,
            A.OBSERVACION, U.NOMBRE_COMPLETO AS RESPONSABLE, M.CODIGO_UNIDAD
          FROM AJUSTE_INVENTARIO A
          JOIN PRODUCTO P ON P.ID_PRODUCTO = A.ID_PRODUCTO
          JOIN UNIDAD_MEDIDA M ON M.ID_UNIDAD = P.ID_UNIDAD
          JOIN TIPO_AJUSTE_STOCK T ON T.ID_TIPO_AJUSTE = A.ID_TIPO_AJUSTE
          JOIN USUARIO U ON U.ID_USUARIO = A.ID_USUARIO
          ORDER BY A.FECHA_HORA_AJUSTE DESC, A.ID_AJUSTE DESC
          OFFSET p_desplazamiento ROWS FETCH NEXT p_limite ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_INVENTARIO_ARTICULO(
  p_actorId IN NUMBER, p_tipoArticulo IN VARCHAR2, p_articuloId IN NUMBER, p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  IF p_tipoArticulo = 'PRODUCTO' THEN
    OPEN p_resultado FOR
      SELECT P.STOCK_ACTUAL, U.PERMITE_DECIMALES
      FROM PRODUCTO P JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
      WHERE P.ID_PRODUCTO = p_articuloId AND P.ESTADO_PRODUCTO = 'S';
  ELSE
    OPEN p_resultado FOR
      SELECT I.STOCK_ACTUAL, U.PERMITE_DECIMALES
      FROM INSUMO I JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = I.ID_UNIDAD
      WHERE I.ID_INSUMO = p_articuloId AND I.ESTADO_ACTIVO = 'S';
  END IF;
END;
/
