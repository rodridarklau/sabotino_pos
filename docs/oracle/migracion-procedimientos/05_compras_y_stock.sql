-- Lecturas de Compras y catálogos de stock compartidos con Inventario.

CREATE OR REPLACE PROCEDURE SAB_API_STOCK_PRODUCTOS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT P.ID_PRODUCTO, P.NOMBRE_PRODUCTO, P.CODIGO_BARRA,
             P.STOCK_ACTUAL, P.STOCK_CRITICO, U.CODIGO_UNIDAD, U.PERMITE_DECIMALES
      FROM PRODUCTO P JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = P.ID_UNIDAD
      WHERE P.ESTADO_PRODUCTO = 'S' ORDER BY P.NOMBRE_PRODUCTO, P.ID_PRODUCTO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_STOCK_INSUMOS(
  p_actorId IN NUMBER, p_incluirInactivos IN NUMBER, p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  IF p_incluirInactivos = 1 THEN
    OPEN p_resultado FOR
      SELECT I.ID_INSUMO, I.NOMBRE_INSUMO, I.STOCK_ACTUAL,
               I.STOCK_CRITICO, I.ID_PROVEEDOR, I.COSTO_UNITARIO,
               U.CODIGO_UNIDAD, U.PERMITE_DECIMALES, I.ESTADO_ACTIVO FROM INSUMO I JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = I.ID_UNIDAD ORDER BY I.NOMBRE_INSUMO, I.ID_INSUMO;
  ELSE
    OPEN p_resultado FOR
      SELECT I.ID_INSUMO, I.NOMBRE_INSUMO, I.STOCK_ACTUAL,
               I.STOCK_CRITICO, I.ID_PROVEEDOR, I.COSTO_UNITARIO,
               U.CODIGO_UNIDAD, U.PERMITE_DECIMALES FROM INSUMO I JOIN UNIDAD_MEDIDA U ON U.ID_UNIDAD = I.ID_UNIDAD WHERE I.ESTADO_ACTIVO = 'S' ORDER BY I.NOMBRE_INSUMO, I.ID_INSUMO;
  END IF;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_COMPRAS_PROVEEDORES(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT ID_PROVEEDOR, RAZON_SOCIAL, RUT_PROVEEDOR
           FROM PROVEEDOR ORDER BY RAZON_SOCIAL;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_COMPRAS_HISTORIAL(
  p_actorId IN NUMBER,
  p_desplazamiento IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT
              A.ID_ABASTECIMIENTO,
              TO_CHAR(A.FECHA_COMPRA, 'DD/MM/YYYY HH24:MI') AS FECHA_COMPRA,
              P.NOMBRE_PRODUCTO,
              U.CODIGO_UNIDAD,
              PR.RAZON_SOCIAL AS PROVEEDOR,
              US.NOMBRE_COMPLETO AS RESPONSABLE,
              A.CANTIDAD_COMPRADA,
              A.COSTO_UNITARIO_COMPRA,
              ROUND(
                A.CANTIDAD_COMPRADA * A.COSTO_UNITARIO_COMPRA,
                2
              ) AS TOTAL
           FROM ABASTECIMIENTO_PROVEEDOR A

           JOIN PRODUCTO P
             ON A.ID_PRODUCTO = P.ID_PRODUCTO

           JOIN UNIDAD_MEDIDA U
             ON P.ID_UNIDAD = U.ID_UNIDAD

           JOIN PROVEEDOR PR
             ON A.ID_PROVEEDOR = PR.ID_PROVEEDOR

           JOIN USUARIO US
             ON A.ID_USUARIO = US.ID_USUARIO

           ORDER BY A.FECHA_COMPRA DESC,
                    A.ID_ABASTECIMIENTO DESC

           OFFSET p_desplazamiento ROWS FETCH NEXT 101 ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_PROVEEDOR_PRODUCTOS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT A.ID_PROVEEDOR, P.ID_PRODUCTO, P.NOMBRE_PRODUCTO FROM (SELECT ID_PRODUCTO, ID_PROVEEDOR FROM (
      SELECT A.ID_PRODUCTO, A.ID_PROVEEDOR, ROW_NUMBER() OVER (
        PARTITION BY A.ID_PRODUCTO ORDER BY A.FECHA_COMPRA DESC NULLS LAST, A.ID_ABASTECIMIENTO DESC
      ) AS POSICION FROM ABASTECIMIENTO_PROVEEDOR A
    ) WHERE POSICION = 1) A
           JOIN PRODUCTO P ON P.ID_PRODUCTO = A.ID_PRODUCTO ORDER BY P.NOMBRE_PRODUCTO, P.ID_PRODUCTO;
END;
/
