-- Consultas de gestión de vendedores y sus horarios.

CREATE OR REPLACE PROCEDURE SAB_API_VENDEDORES(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT U.ID_USUARIO, U.RUT_USUARIO, U.NOMBRE_COMPLETO,
        U.USERNAME, U.ESTADO_USUARIO FROM USUARIO U JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
      WHERE R.NOMBRE_ROL = 'VENDEDOR' ORDER BY U.NOMBRE_COMPLETO, U.ID_USUARIO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENDEDOR_HORARIOS(
  p_actorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT H.ID_HORARIO, H.ID_USUARIO, H.ID_CAJA, C.NOMBRE_CAJA,
          H.DIA_SEMANA, H.HORA_INICIO, H.HORA_FIN, H.ESTADO_ACTIVO
        FROM HORARIO_VENDEDOR H JOIN CAJA_TERMINAL C ON C.ID_CAJA = H.ID_CAJA
        JOIN USUARIO U ON U.ID_USUARIO = H.ID_USUARIO JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
        WHERE R.NOMBRE_ROL = 'VENDEDOR' ORDER BY H.HORA_INICIO, H.ID_HORARIO;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENDEDOR_ROL(
  p_actorId IN NUMBER,
  p_id IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT U.ID_ROL FROM USUARIO U JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
      WHERE R.NOMBRE_ROL = 'VENDEDOR' AND U.ID_USUARIO = p_id;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENDEDOR_DUPLICADO(
  p_actorId IN NUMBER,
  p_usuario IN VARCHAR2,
  p_id IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT ID_USUARIO FROM USUARIO
          WHERE UPPER(USERNAME) = UPPER(p_usuario) AND (p_id IS NULL OR ID_USUARIO <> p_id)
          FETCH FIRST 1 ROW ONLY;
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENDEDOR_HORARIO(
  p_actorId IN NUMBER,
  p_id IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT H.ID_HORARIO FROM HORARIO_VENDEDOR H
        JOIN USUARIO U ON U.ID_USUARIO = H.ID_USUARIO JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
        WHERE H.ID_HORARIO = p_id AND R.NOMBRE_ROL = 'VENDEDOR';
END;
/

CREATE OR REPLACE PROCEDURE SAB_API_VENDEDOR_EXISTE(
  p_actorId IN NUMBER,
  p_vendedorId IN NUMBER,
  p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
  SAB_VALIDAR_DUENO(p_actorId);
  OPEN p_resultado FOR
    SELECT U.ID_USUARIO FROM USUARIO U JOIN ROL_USUARIO R ON R.ID_ROL = U.ID_ROL
      WHERE R.NOMBRE_ROL = 'VENDEDOR' AND U.ID_USUARIO = p_vendedorId;
END;
/
